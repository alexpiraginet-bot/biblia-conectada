import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dryRun = process.argv.includes('--dry-run');
const arg = process.argv.slice(2).find((item) => item !== '--dry-run');
const root = resolve(arg ?? join(dirname(fileURLToPath(import.meta.url)), '../..'));
if (!dryRun && process.platform !== 'darwin') {
  throw new Error('Run configuration on macOS. Use --dry-run to validate paths without writing.');
}
const toolRoot = join(root, 'tools/ios-mcp');
const cli = join(toolRoot, 'node_modules/mobilebuildmcp/build/cli.js');
const quote = (value) => JSON.stringify(value);
const config = `# Generated by scripts/ios/configure-mcp.mjs; local paths, no secrets.\n` +
`[mcp_servers.biblia_xcode]\ncommand = "/usr/bin/xcrun"\nargs = ["mcpbridge"]\nstartup_timeout_sec = 30\ntool_timeout_sec = 600\n\n` +
`[mcp_servers.biblia_mobilebuild]\ncommand = ${quote(process.execPath)}\nargs = [${quote(cli)}, "mcp"]\ncwd = ${quote(root)}\nstartup_timeout_sec = 30\ntool_timeout_sec = 600\n\n` +
`[mcp_servers.biblia_mobilebuild.env]\nMOBILEBUILDMCP_SENTRY_DISABLED = "true"\nMOBILEBUILDMCP_CWD = ${quote(root)}\n`;
const workflowConfig = `# No xcode-ide proxy: use the separate official Apple MCP.\nschemaVersion: 1\nsentryDisabled: true\nenabledWorkflows: ['simulator', 'ui-automation', 'debugging']\n`;
const skill = await readFile(join(toolRoot, 'upstream-skill/SKILL.md'), 'utf8');
const files = [
  [join(root, '.codex/config.toml'), config],
  [join(root, '.mobilebuildmcp/config.yaml'), workflowConfig],
  [join(root, '.agents/skills/mobilebuildmcp/SKILL.md'), skill],
];

// Check all conflicts before writing anything. Never replace another session's configuration.
for (const [path, content] of files) {
  let previous;
  try { previous = await readFile(path, 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (previous !== undefined && previous !== content) {
    throw new Error(`Existing configuration differs. Review and merge it manually: ${path}`);
  }
}
if (!dryRun) {
  await access(cli);
  for (const [path, content] of files) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content, { mode: 0o600 });
  }
}
console.log(`${dryRun ? 'Dry run: no files written' : 'Configuration written'}; ${files.length} project-local files; telemetry disabled.`);
