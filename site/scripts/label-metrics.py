#!/usr/bin/env python3
"""Advance widths and kerning of the two faces used by the Explorar map labels, read from the site's own WOFF2 files.

The map layout (src/lib/explore/atlas.ts, run by the pages on the server) places every label at its real width in the
real font with this table, and the layout test (tests/explore-layout.test.ts) checks all 1,189 chapters with it. The
table records the SHA-256 of each font file and the test fails when a font changes, until this script is run again.

Not part of `npm run build` (Python is not on the build machine); the output is committed.
  requirements: python3 with fonttools 4.60.1 + brotli 1.1.0 (the same as scripts/subset-fonts.sh)
  usage (in site/): python3 scripts/label-metrics.py
"""
import hashlib
import json
import os
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(SITE, "src", "lib", "explore", "label-metrics.json")
FACES = {
    # chapter and medallion names: --font-display (Newsreader, static instance opsz 72 / wght 440)
    "title": {"file": "src/fonts/Newsreader-Display.woff2", "axes": None},
    # count lines under the names: --font-ui (Space Grotesk) at weight 400
    "ui": {"file": "src/fonts/SpaceGrotesk-VF.woff2", "axes": {"wght": 400}},
}


def charset():
    """Every character a label can hold: book names, digits, and the words of the count lines."""
    books = json.load(open(os.path.join(SITE, "src/data/generated/books.json"), encoding="utf-8"))
    # "-": a sum of votes can be negative, and Intl.NumberFormat writes the hyphen-minus
    chars = set("0123456789 .,:·–-")
    for b in books:
        chars.update(b["name"])
        chars.update(b["abbr"])
    chars.update("abcdefghijklmnopqrstuvwxyzáàâãéêíóôõúç")
    chars.update("ABCDEFGHIJKLMNOPQRSTUVWXYZÁÂÉÊÍÓÔÚÇ")
    return sorted(chars)


def kern_pairs(font, glyphs):
    """Horizontal kerning of the GPOS 'kern' feature for pairs of the given glyphs (first match per lookup)."""
    if "GPOS" not in font:
        return {}
    table = font["GPOS"].table
    lookups = sorted({i for fr in table.FeatureList.FeatureRecord if fr.FeatureTag == "kern" for i in fr.Feature.LookupListIndex})
    wanted = set(glyphs)
    out = {}
    for li in lookups:
        lookup = table.LookupList.Lookup[li]
        subtables = [st.ExtSubTable if lookup.LookupType == 9 else st for st in lookup.SubTable]
        for g1 in glyphs:
            for g2 in glyphs:
                for st in subtables:
                    if st.LookupType != 2 or g1 not in st.Coverage.glyphs:
                        continue
                    if st.Format == 1:
                        ps = st.PairSet[st.Coverage.glyphs.index(g1)]
                        rec = next((r for r in ps.PairValueRecord if r.SecondGlyph == g2), None)
                        if rec is None:
                            continue
                        v = getattr(rec.Value1, "XAdvance", 0) or 0 if rec.Value1 else 0
                    else:
                        c1 = st.ClassDef1.classDefs.get(g1, 0)
                        c2 = st.ClassDef2.classDefs.get(g2, 0)
                        r = st.Class1Record[c1].Class2Record[c2]
                        v = getattr(r.Value1, "XAdvance", 0) or 0 if r.Value1 else 0
                    if v and g2 in wanted:
                        out[(g1, g2)] = out.get((g1, g2), 0) + v
                    break
    return out


def face(spec, chars):
    path = os.path.join(SITE, spec["file"])
    sha = hashlib.sha256(open(path, "rb").read()).hexdigest()
    font = TTFont(path)
    if spec["axes"]:
        font = instancer.instantiateVariableFont(font, spec["axes"])
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    missing = [c for c in chars if ord(c) not in cmap]
    if missing:
        sys.exit(f"{spec['file']}: no glyph for {missing}")
    glyph = {c: cmap[ord(c)] for c in chars}
    advances = {c: hmtx[glyph[c]][0] for c in chars}
    by_glyph = {g: c for c, g in glyph.items()}
    kerning = {by_glyph[a] + by_glyph[b]: v for (a, b), v in sorted(kern_pairs(font, sorted(set(glyph.values()))).items())}
    os2 = font["OS/2"]
    return {
        "file": spec["file"],
        "sha256": sha,
        "axes": spec["axes"],
        "unitsPerEm": font["head"].unitsPerEm,
        "ascender": os2.sTypoAscender,
        "descender": os2.sTypoDescender,
        "advances": advances,
        "kerning": kerning,
    }


def main():
    chars = charset()
    out = {
        "note": "Generated by scripts/label-metrics.py from the site's WOFF2 files; do not edit by hand.",
        "faces": {name: face(spec, chars) for name, spec in FACES.items()},
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1, sort_keys=True)
        f.write("\n")
    for name, fc in out["faces"].items():
        print(f"{name}: {len(fc['advances'])} characters, {len(fc['kerning'])} kerning pairs, sha256 {fc['sha256'][:12]}…")


if __name__ == "__main__":
    main()
