// Writes src/styles/tokens.css from src/styles/tokens.json, the tokens of the "Atlas" design system (the same file the
// design-system page publishes). Every theme block spells out every colour, so no token of one theme refers to another.
// Noite is the default, including without JavaScript. An explicit Sistema choice follows the device; a stored choice
// (data-theme on <html> and <body>) wins either way. <body> gets its own copy of the values whenever <html> has no
// choice, so a change of the device's setting recomputes it too (the stale colours of 19/10 came from inheritance).
//   npx tsx scripts/tokens-css.ts            writes the file
//   tests/tokens.test.ts                     checks the file is what this script writes
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
export const TOKENS_JSON = join(ROOT, "src/styles/tokens.json");
export const TOKENS_CSS = join(ROOT, "src/styles/tokens.css");

type Value = string | Record<string, string>;
type Entry = { name: string; value: Value; usage?: string };
export type Tokens = {
  color: { themes: { id: string; name: string }[]; tokens: Entry[] };
  shadow: { tokens: Entry[] };
  type: {
    families: Record<string, string>;
    groups: { styles: { name: string; fontSize: string; lineHeight: number; fluid?: string }[] }[];
  };
  [family: string]: unknown;
};

/** next/font sets these on <html>; the families fall back to the stacks in tokens.json */
const FONT_VARS: Record<string, string> = { display: "--nf-display", reading: "--nf-reading", ui: "--nf-ui" };

export function tokensCss(t: Tokens = JSON.parse(readFileSync(TOKENS_JSON, "utf8")) as Tokens): string {
  const [noite, dia] = t.color.themes.map((x) => x.id);
  const at = (e: Entry, theme: string) => (typeof e.value === "string" ? e.value : (e.value[theme] ?? e.value[noite]));
  const themed = (theme: string, indent: string) => {
    const lines = [
      ...t.color.tokens.map((e) => `--${e.name}: ${at(e, theme)};`),
      ...t.shadow.tokens.map((e) => `--${e.name}: ${at(e, theme)};`),
      `color-scheme: ${theme === dia ? "light" : "dark"};`,
    ];
    return lines.map((l) => indent + l).join("\n");
  };
  const fixed: string[] = [];
  for (const family of ["spacing", "radius", "layout", "duration"]) {
    for (const e of (t[family] as { tokens: Entry[] }).tokens) fixed.push(`--${e.name}: ${e.value as string};`);
  }
  // type sizes in rem, so they follow the reader's own font size; the fluid ones grow with the viewport
  for (const style of t.type.groups.flatMap((g) => g.styles)) {
    fixed.push(`--fs-${style.name}: ${style.fluid ?? `${parseFloat(style.fontSize) / 16}rem`};`);
    fixed.push(`--lh-${style.name}: ${style.lineHeight};`);
  }
  for (const [key, stack] of Object.entries(t.type.families)) {
    const fallback = stack.split(",").slice(1).join(",").trim();
    fixed.push(`--font-${key}: var(${FONT_VARS[key]}), ${fallback};`);
  }
  return [
    "/* Generated by scripts/tokens-css.ts from src/styles/tokens.json. Do not edit by hand. */",
    "",
    ":root,",
    ":root:not([data-theme]) body {",
    themed(noite, "  "),
    ...fixed.map((l) => "  " + l),
    "}",
    "",
    `@media (prefers-color-scheme: light) {`,
    `  :root[data-theme="sistema"],`,
    `  :root[data-theme="sistema"] body {`,
    themed(dia, "    "),
    "  }",
    "}",
    "",
    `[data-theme="${dia}"] {`,
    themed(dia, "  "),
    "}",
    "",
    `[data-theme="${noite}"] {`,
    themed(noite, "  "),
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  writeFileSync(TOKENS_CSS, tokensCss());
  console.log(`[tokens] wrote ${TOKENS_CSS}`);
}
