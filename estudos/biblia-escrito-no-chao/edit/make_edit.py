#!/usr/bin/env python3
"""Writes edit/edit.jsx, the Higgsedit project of "Escrito no chão" (native CLI v0.14.0, Higgsfield sandbox), from
renders/.film/plan.json: the 26 shots on the spine, cut on the frame; every line of type as a native text clip that
arrives on its word; the mix on its own lane (placed after the build, see edit/run.sh). Nothing is typed by hand here:
times, positions, sizes and colours are the plan's.

  python3 -I edit/make_edit.py        -> edit/edit.jsx
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
P = json.load(open(ROOT / "renders/.film/plan.json"))
FPS = P["fps"]
EPS = 0.002
shots = [{"id": s["id"], "at": s["f0"] / FPS, "dur": s["frames"] / FPS} for s in P["shots"]]
blocks = []
for b in P["blocks"]:
    f0 = round(b["t0"] * FPS); f1 = round(b["t1"] * FPS)                 # blocks live on whole frames, like the cuts
    cut_start = any(abs(s["f0"] - f0) == 0 for s in P["shots"])
    lines = []
    for l in b["lines"]:
        at = max(0, round(l["t0"] * FPS) - f0) / FPS
        lines.append({"text": l["text"], "face": l["face"], "size": l["size"], "color": l["color"], "y": l["y"], "at": round(at, 4),
                      # the title is whole on frame 0; a line that arrives with a cut is readable on the cut frame
                      # (it only settles); a line that arrives on a word pops in
                      "enter": "none" if f0 == 0 else ("cut" if at == 0 and cut_start else "word")})
    # EPS: at + dur must stay below the next frame time, or float rounding keeps the block one frame into the next shot
    blocks.append({"id": b["id"], "at": f0 / FPS, "dur": round((f1 - f0) / FPS - EPS, 6), "lines": lines})
data = {"dur": P["frames"] / FPS, "fps": FPS, "shots": shots, "blocks": blocks, "faces": P["faces"], "tag": P["tag"]}

JSX = '''// "Escrito no chão" (Bíblia Conectada, video 11): the edit, in Higgsedit. Generated by edit/make_edit.py from
// renders/.film/plan.json; run with edit/run.sh inside the Higgsfield sandbox. Do not edit by hand.
const R = process.env.ENC_ROOT || "/home/user/enc";
const PLAN = %s;
const SHADOW = { x: 3, y: 4, blur: 7, color: "#140a04e0" };

export default async ({ project }) => {
  const p = await project({ dir: R + "/film", size: "1080x1920", fps: PLAN.fps, background: "#1a0f08" });
  const face = {};
  for (const [k, f] of Object.entries(PLAN.faces)) face[k] = { h: await p.add(`${R}/fonts/${f.file}`), wght: f.wght };

  // ---- the cut: one clip per shot on the spine, frame-accurate (the durations are whole frames)
  for (const s of PLAN.shots) {
    const h = await p.add(`${R}/shots/${s.id}.mp4`);
    p.cut(h, { from: 0, dur: s.dur, at: s.at, fit: "cover" });
  }

  // ---- the type: one overlay per block; each line is its own frame, so it can arrive on its word
  for (const b of PLAN.blocks) {
    p.compose(
      <frame layout="none" width={1080} height={1920}>
        {b.lines.map((l, i) => {
          const box = Math.round(l.size * 1.4), dur = b.dur - l.at;
          const typo = { fontAssetId: face[l.face].h.id, ...(face[l.face].wght ? { axes: { wght: face[l.face].wght } } : {}) };
          const txt = (
            <text x={0} y={0} width={1000} height={box} fontSize={l.size} lineHeight={1.0} align="center" color={l.color}
              typography={typo} shadow={SHADOW}>{l.text}</text>
          );
          const ENTER = { cut: { from: { y: 8, scale: 0.955, opacity: 0.6 }, duration: 0.10 }, word: { from: { y: 16, scale: 0.92, opacity: 0 }, duration: 0.14 } }[l.enter];
          return ENTER ? (
            <frame name={`${b.id}-${i}`} layout="none" x={40} y={l.y} width={1000} height={box} origin="center" at={l.at} duration={dur}
              motion={{ enter: { ...ENTER, duration: Math.min(ENTER.duration, dur) } }}>{txt}</frame>
          ) : (
            <frame name={`${b.id}-${i}`} layout="none" x={40} y={l.y} width={1000} height={box} at={l.at} duration={dur}>{txt}</frame>
          );
        })}
      </frame>,
      { at: b.at, dur: b.dur, name: b.id }
    );
  }
  // ---- the mark of the series on illustrated scenes: the whole film
  const tag = await p.add(`${R}/fonts/${PLAN.tag.file}`);
  p.compose(
    <text x={PLAN.tag.right - 400} y={PLAN.tag.y} width={400} height={32} fontSize={PLAN.tag.size} lineHeight={1.0} align="right" letterSpacing={PLAN.tag.size * 0.12}
      color={PLAN.tag.color} opacity={PLAN.tag.opacity} typography={{ fontAssetId: tag.id }} shadow={{ x: 1, y: 2, blur: 4, color: "#140a04c0" }}>{PLAN.tag.text}</text>,
    { at: 0, dur: PLAN.dur - 0.002, name: "tag" }
  );
  const still = (process.env.STILLS || "").split(",").filter(Boolean);
  for (const t of still) await p.frame(Number(t), `renders/f-${Number(t).toFixed(2)}.png`);
  console.log(JSON.stringify({ duration: p.duration(), shots: PLAN.shots.length, blocks: PLAN.blocks.length, stills: still.length }));
};
''' % json.dumps(data, ensure_ascii=False)
(ROOT / "edit/edit.jsx").write_text(JSX)

RUN = '''#!/bin/bash
# The edit, inside the Higgsfield sandbox (Higgsedit native CLI v0.14.0): build the timeline from edit.jsx, put the mix
# on its own lane, render the master. Inputs in $ENC_ROOT: shots/*.mp4, fonts/*.ttf, mix.wav, edit.jsx.
#   bash run.sh build [t1,t2,...]   -> the project + PNG stills at those times
#   bash run.sh render              -> film/renders/escrito-no-chao-master.mp4
set -euo pipefail
export ENC_ROOT="${ENC_ROOT:-/home/user/enc}"; cd "$ENC_ROOT"
case "${1:-build}" in
  build)
    rm -rf film; STILLS="${2:-}" higgsedit build edit.jsx
    ID=$(higgsedit import film "$ENC_ROOT/mix.wav" | python3 -c "import json,sys; print(json.load(sys.stdin)['imported'][0]['id'])")
    higgsedit do film place --assetId "$ID" --at 0 --duration __DUR__      # whole frames: the film ends with its last shot
    higgsedit check film;;
  render)
    higgsedit render film --out renders/escrito-no-chao-master.mp4 --bitrate 20M
    ffprobe -v error -show_entries stream=codec_name,width,height,r_frame_rate,nb_frames,duration,bit_rate -of json film/renders/escrito-no-chao-master.mp4;;
esac
'''
(ROOT / "edit/run.sh").write_text(RUN.replace("__DUR__", f"{data['dur']:.4f}"))
print(f"edit.jsx: {len(shots)} shots, {len(blocks)} blocks, {sum(len(b['lines']) for b in blocks)} lines, {data['dur']:.3f} s")
